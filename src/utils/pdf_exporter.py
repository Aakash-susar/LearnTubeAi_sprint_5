class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and render 'Page X of Y' and running headers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#6b7280"))

        # Top Header (Only on page 2 and later)
        if self._pageNumber > 1:
            self.drawString(54, 755, "LearnTube AI • Structured Study Notes")
            self.setStrokeColor(colors.HexColor("#e5e7eb"))
            self.setLineWidth(0.5)
            self.line(54, 748, 558, 748)

        # Bottom Footer (All pages)
        self.setStrokeColor(colors.HexColor("#e5e7eb"))
        self.setLineWidth(0.5)
        self.line(54, 45, 558, 45)

        self.drawString(54, 32, "Generated by LearnTube AI — AI-Powered YouTube Learning Assistant")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 32, page_str)

        self.restoreState()


def _clean_emojis(text: str) -> str:
    """Remove or sanitize emojis and special unicode symbols that are unsupported by standard PDF core fonts."""
    if not text:
        return ""
    emoji_pattern = re.compile(
        "["
        "\U00010000-\U0010ffff"
        "\u2600-\u27bf"
        "\u2300-\u23ff"
        "\u2b50-\u2b55"
        "\u200d"
        "\ufe0f"
        "]+",
        flags=re.UNICODE
    )
    # Remove emojis and extra double spaces
    cleaned = emoji_pattern.sub("", text)
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    return cleaned


def _format_inline_markdown(text: str) -> str:
    """Safely convert common inline Markdown tags into ReportLab XML formatting."""
    # 0. Sanitize non-standard unicode/emojis
    text = _clean_emojis(text)

    # 1. Escape XML characters first
    text = html.escape(text, quote=False)

    # 2. Bold: **text** or __text__
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    text = re.sub(r'__(.+?)__', r'<b>\1</b>', text)

    # 3. Italic: *text* or _text_
    text = re.sub(r'\*([^*]+?)\*', r'<i>\1</i>', text)
    text = re.sub(r'_([^_]+?)_', r'<i>\1</i>', text)

    # 4. Inline code: `code`
    text = re.sub(r'`([^`]+?)`', r'<font name="Courier" color="#b91c1c"><b>\1</b></font>', text)

    return text


def generate_summary_pdf(
    summary_text: str,
    metadata: dict = None,
    style_label: str = "Study Notes"
) -> bytes:
    """
    Generate a styled, academic PDF document from a Markdown summary string.
    Returns in-memory PDF bytes suitable for st.download_button.
    """
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    # ---- Styles ----
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#111827'),
        alignment=TA_LEFT,
        spaceAfter=4
    )

    badge_style = ParagraphStyle(
        'BadgeStyle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=11,
        textColor=colors.HexColor('#ffffff'),
        alignment=TA_CENTER
    )

    meta_label_style = ParagraphStyle(
        'MetaLabel',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#4b5563')
    )

    h1_style = ParagraphStyle(
        'H1',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#991b1b'),  # Crimson / Dark Red
        spaceBefore=14,
        spaceAfter=6,
        keepWithNext=True
    )

    h2_style = ParagraphStyle(
        'H2',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#1f2937'),
        spaceBefore=10,
        spaceAfter=4,
        keepWithNext=True
    )

    h3_style = ParagraphStyle(
        'H3',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#374151'),
        spaceBefore=8,
        spaceAfter=3,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor('#1f2937'),
        alignment=TA_JUSTIFY,
        spaceAfter=6
    )

    bullet_style = ParagraphStyle(
        'Bullet',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor('#1f2937'),
        leftIndent=14,
        firstLineIndent=-10,
        spaceAfter=4
    )

    quote_style = ParagraphStyle(
        'Quote',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor('#4b5563'),
        leftIndent=16,
        spaceBefore=4,
        spaceAfter=6
    )

    story = []

    # ---- 1. Header Banner & Metadata ----
    video_title = "Educational Video Summary"
    channel_title = "Unknown Channel"
    if metadata and isinstance(metadata, dict):
        video_title = metadata.get("title") or video_title
        channel_title = metadata.get("channel_title") or channel_title

    clean_video_title = _clean_emojis(video_title)
    clean_channel_title = _clean_emojis(channel_title)
    clean_style_label = _clean_emojis(style_label)

    # Top Brand Bar
    brand_table = Table(
        [
            [
                Paragraph("<b>▶ LearnTube AI</b>", ParagraphStyle('Brand', fontName='Helvetica-Bold', fontSize=12, leading=14, textColor=colors.HexColor('#dc2626'))),
                Paragraph(datetime.now().strftime("%B %d, %Y"), ParagraphStyle('Date', fontName='Helvetica', fontSize=8.5, leading=11, textColor=colors.HexColor('#6b7280'), alignment=TA_RIGHT))
            ]
        ],
        colWidths=[300, 204]
    )
    brand_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
    ]))
    story.append(brand_table)
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#dc2626'), spaceBefore=2, spaceAfter=10))

    # Video Title
    story.append(Paragraph(html.escape(clean_video_title), title_style))

    # Metadata Info Box
    badge_cell = Paragraph(f"<b>{html.escape(clean_style_label)}</b>", badge_style)
    badge_table = Table([[badge_cell]], colWidths=[120])
    badge_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#dc2626')),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))

    info_text = f"<b>Instructor / Channel:</b> {html.escape(clean_channel_title)}"
    meta_table = Table(
        [
            [Paragraph(info_text, meta_label_style), badge_table]
        ],
        colWidths=[384, 120]
    )
    meta_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 2),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#e5e7eb'), spaceBefore=4, spaceAfter=12))

    # ---- 2. Parse Summary Content ----
    lines = summary_text.split('\n')
    for raw_line in lines:
        line = raw_line.strip()
        if not line:
            story.append(Spacer(1, 3))
            continue

        # Headings
        if line.startswith('### '):
            clean_text = _format_inline_markdown(line[4:])
            story.append(Paragraph(clean_text, h3_style))
        elif line.startswith('## '):
            clean_text = _format_inline_markdown(line[3:])
            story.append(Paragraph(clean_text, h2_style))
        elif line.startswith('# '):
            clean_text = _format_inline_markdown(line[2:])
            story.append(Paragraph(clean_text, h1_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#fca5a5'), spaceBefore=2, spaceAfter=6))
        # Bullet Points
        elif line.startswith(('-', '*', '•')):
            clean_text = _format_inline_markdown(line.lstrip('-*• '))
            story.append(Paragraph(f"• &nbsp; {clean_text}", bullet_style))
        # Numbered list
        elif re.match(r'^\d+\.\s+', line):
            m = re.match(r'^(\d+\.)\s+(.+)$', line)
            if m:
                num_prefix, content = m.groups()
                clean_text = _format_inline_markdown(content)
                story.append(Paragraph(f"<b>{num_prefix}</b> {clean_text}", bullet_style))
            else:
                story.append(Paragraph(_format_inline_markdown(line), body_style))
        # Blockquote
        elif line.startswith('>'):
            clean_text = _format_inline_markdown(line.lstrip('> '))
            story.append(Paragraph(f"<i>{clean_text}</i>", quote_style))
        # Normal Paragraph
        else:
            clean_text = _format_inline_markdown(line)
            story.append(Paragraph(clean_text, body_style))

    # ---- 3. Build Document ----
    doc.build(story, canvasmaker=NumberedCanvas)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
